## 核心特性
### 1. 统一入口
用户只需管理**一个平台API Key**，即可访问所有已配置的AI厂商服务。平台根据请求中的 `model` 字段自动路由到对应厂商。

### 2. 多厂商支持
通过适配器模式，平台可轻松支持多个AI厂商。新增厂商只需实现一个适配器类，无需修改现有代码。

### 3. 安全加固
- **平台密钥**：bcrypt单向哈希存储，即使数据库泄露也无法恢复
- **厂商密钥**：Fernet对称加密存储，仅在内存中解密使用
- **全链路TLS**：Nginx到Uvicorn全链路加密传输

### 4. 成本管控
- 双层限流（频率 + 配额）
- 每次调用记录Token消耗
- 支持按用户/厂商维度统计用量

### 5. 审计追踪
所有API调用记录在 `request_logs` 表中，包含用户、厂商、模型、Token数、延迟等完整信息。

