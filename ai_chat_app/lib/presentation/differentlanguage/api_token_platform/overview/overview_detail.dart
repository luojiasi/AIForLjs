## 快速体验

### 5分钟启动
```bash
cd differentlanguage/api_token_platform_backend
pip install -r requirements.txt
cp .env.example .env
# 编辑 .env 填入你的 OPENAI_API_KEY
uvicorn app.main:app --reload --port 8000
```

访问 http://localhost:8000/docs 即可看到自动生成的API文档。

### 基本使用流程
1. **注册用户** `POST /auth/register`
2. **创建平台API Key** `POST /auth/api-keys`
3. **使用API Key调用AI** `POST /v1/chat/completions`
4. **查看用量** `GET /usage/stats`

