# 平台概述

## 什么是API Token中转平台？
API Token中转平台是一个统一的AI服务网关，它作为客户端与多个AI厂商之间的中间层，解决了多厂商AI服务接入的核心痛点。

### 它解决什么问题？

在企业或团队使用多个AI服务时，面临以下挑战：
1. **密钥管理混乱**：每个开发者需要持有和管理多个厂商的API Key（OpenAI、Anthropic、Google等），分散管理增加了泄露风险
2. **成本不可见**：各厂商的用量数据分散在不同平台，难以统一审计和成本分析
3. **接口不统一**：OpenAI用的是 `/v1/chat/completions`，Anthropic用的是 `/v1/messages`，每个厂商API格式不同
4. **安全风险集中**：厂商API Key直接暴露在客户端代码中，容易被逆向或泄露
5. **厂商锁定**：应用代码直接依赖某个厂商的SDK，切换厂商成本极高

